-- B1 — Races : retrait des sections éditoriales générées par modèle, sous-catégorie et nom
-- scientifique corrigés.
--
-- Pourquoi : les 1 211 races (identifiants artificiels >= 2 000 000 001) ont reçu, à l'import de
-- breeds-data.json, des sections alimentation / habitat / comportement / santé / législation /
-- reproduction recopiées d'un modèle générique par groupe d'espèces, parfois d'un autre animal
-- (Persan, Abyssin, Bulldog français : « herbivore, foin 80 %, granulés lapin », maladies du
-- lapin ; Poule Sussex : modèle perruche ; Tortue d'Hermann : modèle gecko insectivore) et aux
-- sources génériques non vérifiées (racine wamiz.com, « page de référence »). Règle du dépôt :
-- sans source vérifiée, la donnée reste absente. L'API (v. N) sert alors à la race les sections
-- sourcées de son espèce parente (même nom scientifique). Le seed (createMany skipDuplicates)
-- n'écrase rien : seule une migration corrige la base déjà peuplée.
--
-- Périmètre, sûreté :
--  - uniquement les races ("speciesId" >= 2000000001) ; aucune fiche espèce ni aucune race
--    (SpeciesProfile) n'est supprimée, aucun animal n'est touché ;
--  - une section n'est retirée que si elle porte l'empreinte du modèle (titre de source
--    générique des modèles prisma/templates/*.json ; pour la législation, uniquement les racines
--    https://www.legifrance.gouv.fr / https://inpn.mnhn.fr) : un contenu saisi depuis
--    (POST /species/:id/health, etc.) est conservé ;
--  - nom scientifique et sous-catégorie : mise à jour ciblée par identifiant, seulement si la
--    valeur en base est encore celle de l'import (une correction manuelle n'est pas écrasée) ;
--  - idempotente : rejouée, elle ne trouve plus rien à modifier ;
--  - aucune contrainte touchée (les sections sont des lignes filles sans dépendance).
--
-- Compatibilité N-1 : données seulement, aucun changement de schéma. L'API N-1 renvoie
-- « aucune section » (null) pour ces races, comme pour toute fiche incomplète ; jamais plus la
-- section d'un autre animal.

